const SPLIT_KEYS = EXAM_PAGES.map((page) => page.key);

const esc = (value) => String(value == null ? "" : value).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");

const read = (file) => fs.readFileSync(path.join(ROOT, file), "utf8");

/** A marked block of js/site.js, so the helpers come from the file the browser runs. */
function siteBlock(site, name) {
  const start = site.indexOf(`/* pf:${name}:start`);
  const end = site.indexOf(`/* pf:${name}:end */`);
  if (start < 0 || end <= start) throw new Error(`js/site.js no longer marks its pf:${name} block`);
  return site.slice(start, end);
}

/** A named function or PF assignment lifted out of js/site.js by its opening line. */
function siteFunction(site, opening) {
  const start = site.indexOf(opening);
  if (start < 0) throw new Error(`js/site.js no longer contains "${opening}"`);
  const end = site.indexOf("\n  }", start);
  return site.slice(start, end + 4);
}

function examMarkup() {
  const site = read("js/site.js");
  const context = vm.createContext({
    window: { PF: {} },
    document: { readyState: "loading", addEventListener() {} },
    URL
  });
  vm.runInContext(
    "const PF = window.PF;\n" +
    `${siteFunction(site, "function escapeHtml(value) {")}\nPF.escapeHtml = escapeHtml;\n` +
    `${siteFunction(site, "PF.slug = function (value) {")};\n` +
    `${siteBlock(site, "source-marks")}\n` +
    "PF.classifySource = classifySource; PF.sourceBrand = sourceBrand; PF.sourceMark = sourceMark;",
    context
  );
  new vm.Script(read("js/data/exams.js")).runInContext(context);
  new vm.Script(read("js/exams-page.js")).runInContext(context);
  const { PF, PF_DATA } = context.window;
  if (typeof PF.examMarkup !== "function") throw new Error("js/exams-page.js no longer exposes PF.examMarkup");
  return PF.examMarkup(PF, PF_DATA.exams);
}

/** The hub: a card for each exam page, then the panels that stay on it. */
export function renderExams() {
  const markup = examMarkup();
  const cards = EXAM_PAGES.map((page) => `<a class="topic-card" href="${page.slug}/"><span class="topic-card-name">${esc(page.h1)}</span><span class="topic-card-note">${esc(page.description)}</span></a>`).join("");
  const keys = markup.panelDefinitions.map((definition) => definition.key).filter((key) => !SPLIT_KEYS.includes(key));
  return `<div class="topic-index exam-guides">${cards}</div>${markup.prerendered(keys)}`;
}

