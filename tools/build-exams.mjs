const sameYear = (html) => html.replace(/<span data-year>\d{4}<\/span>/g, "<span data-year></span>").replace(/\?v=[a-f0-9]{12}(?=")/g, "");

function build() {
  const page = fs.readFileSync(PAGE, "utf8");
  const block = `${START}${renderExams()}${END}`;
  const start = page.indexOf(START);
  const end = page.indexOf(END);
  let next;
  if (start >= 0 && end > start) next = page.slice(0, start) + block + page.slice(end + END.length);
  else if (page.includes('<div id="exam-root"></div>')) next = page.replace('<div id="exam-root"></div>', `<div id="exam-root">${block}</div>`);
  else throw new Error("exams/index.html has neither generated exam panels nor an empty #exam-root to fill");
  const stale = [];
  if (next !== page) {
    if (check) stale.push("exams/index.html");
    else fs.writeFileSync(PAGE, next);
  }
  for (const examPage of EXAM_PAGES) {
    const file = path.join(ROOT, "exams", examPage.slug, "index.html");
    const html = renderExamPage(examPage);
    const current = fs.existsSync(file) ? fs.readFileSync(file, "utf8") : "";
    if (sameYear(current) === sameYear(html)) continue;
    if (check) stale.push(path.relative(ROOT, file));
    else {
      fs.mkdirSync(path.dirname(file), { recursive: true });
      fs.writeFileSync(file, html);
    }
  }
  if (check) {
    if (stale.length) {
      console.error(`Exam pages are stale: ${stale.join(", ")}. Run: npm run build:exams`);
      process.exit(1);
    }
    console.log("Exam panels and pages are current.");
    return;
  }
  console.log(`Wrote exams/index.html and ${EXAM_PAGES.length} exam pages.`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) build();
